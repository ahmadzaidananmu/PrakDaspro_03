package Jobsheet2;

public class ContohOperator03 {
    public static void main(String[] args) {
        int A = 60;
        int B = 20;
        int C = 10;

        System.out.println("ARITMETIKA OPERATOR");
        System.out.println("Bilangan A adalah : "+A);
        System.out.println("Bilangan B adalah : "+B);
        System.out.println("Bilangan C adalah : "+C);
        System.out.println(" A + B + C : "+(A+B+C));
        System.out.println(" A - B - C : "+(A-B-C));
        System.out.println("A x C : "+(A*C));
        System.out.println("A / B : "+(A/B));
        System.out.println("A % B : "+(A%B));
        System.out.println("A + B x C : "+(A+B*C));
        System.out.println("(A + B) x C : "+((A+B)*C));
    }
}
